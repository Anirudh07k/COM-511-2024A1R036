# Program to demonstrate type checking and built-in functions

# Different data types
a = 10
b = 10.5
c = "Python"
d = True
e = [10, 20, 30]

# Type checking using type()
print("Type of a:", type(a))
print("Type of b:", type(b))
print("Type of c:", type(c))
print("Type of d:", type(d))
print("Type of e:", type(e))


# Demonstration of built-in functions

print("Absolute value:", abs(-10))
print("Length:", len("Python"))
print("Minimum value:", min(10, 5, 20))
print("Rounded value:", round(12.567, 2))
print("Alphanumeric:", "Python123".isalnum())
print("Type:", type(a))